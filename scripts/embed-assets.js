#!/usr/bin/env bun
// Generate src/embedded-assets.js by scanning ./dist
// Text assets are inlined as JS strings.
// Binary assets (images/fonts) are inlined as base64 → Uint8Array.

import { readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const DIST = join(ROOT, 'dist');
const OUT  = join(ROOT, 'embedded-assets.js');

const TEXT_EXT = new Set(['.html', '.js', '.mjs', '.css', '.json', '.svg', '.txt', '.map']);

if (!existsSync(DIST)) {
    console.error(`✗ dist/ not found. Run \`bun run build\` first.`);
    process.exit(1);
}

function walk(dir) {
    const out = [];
    for (const name of readdirSync(dir)) {
        const full = join(dir, name);
        const stat = statSync(full);
        if (stat.isDirectory()) {
            out.push(...walk(full));
        } else if (stat.isFile()) {
            out.push(full);
        }
    }
    return out;
}

const files = walk(DIST).sort();

let body = '// AUTO-GENERATED by scripts/embed-assets.js — do not edit by hand.\n';
body += '// Inlined snapshot of ./dist for the single-file Bun executable.\n\n';
body += 'export const ASSETS = new Map();\n\n';

let totalBytes = 0;
const summaries = [];

for (const abs of files) {
    const rel = relative(DIST, abs).replaceAll('\\', '/'); // POSIX-style key
    const buf = await Bun.file(abs).bytes();
    totalBytes += buf.byteLength;
    const ext = extname(rel).toLowerCase();
    const isText = TEXT_EXT.has(ext);
    summaries.push({ rel, bytes: buf.byteLength, kind: isText ? 'text' : 'bin' });

    if (isText) {
        const text = new TextDecoder('utf-8').decode(buf);
        body += `ASSETS.set(${JSON.stringify(rel)}, { kind: 'text', bytes: ${buf.byteLength}, body: ${JSON.stringify(text)} });\n`;
    } else {
        const b64 = Buffer.from(buf).toString('base64');
        body += `ASSETS.set(${JSON.stringify(rel)}, { kind: 'bin',  bytes: ${buf.byteLength}, body: ${JSON.stringify(b64)} });\n`;
    }
}

writeFileSync(OUT, body, 'utf-8');

const kb = (n) => (n / 1024).toFixed(1) + ' KB';
console.log(`✓ Embedded ${files.length} files (${kb(totalBytes)}) into ${relative(ROOT, OUT)}`);
for (const s of summaries) {
    console.log(`   ${s.kind === 'text' ? '📄' : '🖼 '} ${s.rel}  (${kb(s.bytes)})`);
}
